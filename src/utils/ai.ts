export function generateArticle(topic: string, url: string, anchor: string, category: string): { title: string; content: string; keywords: string[] } {
  const templateIndex = Math.floor(Math.random() * articleStructures.length)
  const titleVariations = [
    `${topic}: The Complete ${new Date().getFullYear()} Guide`,
    `How to Master ${topic} — Expert Strategies Revealed`,
    `${topic}: Proven Methods for Real Results`,
    `The Ultimate ${topic} Playbook`,
    `${topic} Demystified: A Practical Approach`,
  ]
  const title = titleVariations[Math.floor(Math.random() * titleVariations.length)]
  const content = articleStructures[templateIndex](topic, url, anchor || topic)
  
  const keywordSets: Record<string, string[]> = {
    Technology: ['innovation', 'digital transformation', 'automation', 'AI', 'software'],
    Business: ['strategy', 'growth', 'ROI', 'leadership', 'management'],
    Health: ['wellness', 'nutrition', 'fitness', 'mental health', 'lifestyle'],
    General: ['success', 'productivity', 'growth', 'strategy', 'improvement'],
    Education: ['learning', 'skills', 'development', 'training', 'knowledge'],
    Lifestyle: ['wellness', 'balance', 'mindfulness', 'habits', 'growth'],
  }
  
  return {
    title,
    content,
    keywords: keywordSets[category] || keywordSets['General'],
  }
}

